"""Phase 4B only: standard-library TCP client, no camera or gesture imports."""
import argparse
import json
import math
import socket
import sys
import uuid
from java_protocol import JsonConnection


def send_request(message, port=5050, timeout=5):
    """Send one newline-delimited JSON request and await its final result.

    No automatic retries: a lost acknowledgement does not prove a click failed.
    Reuse the same event ID to safely retry against the same Java process.
    """
    with JsonConnection(port, timeout) as connection:
        print(f'Connected to 127.0.0.1:{port}')
        return connection.request(message, on_sent=lambda: print(
            'Message sent; waiting for Java execution result (delivery is not an action confirmation).'))


def main(argv=None):
    parser = argparse.ArgumentParser(description='Send a simulated SELECT to the original Java game (no webcam).')
    parser.add_argument('--x', type=float)
    parser.add_argument('--y', type=float)
    parser.add_argument('--id', help='Unique event ID; autogenerated unless supplied. Reuse only for a retry.')
    parser.add_argument('--port', type=int, default=5050)
    parser.add_argument('--timeout', type=float, default=5)
    parser.add_argument('--info', action='store_true', help='List current visible controls and valid viewport coordinates; no click')
    args = parser.parse_args(argv)
    if not 1 <= args.port <= 65535 or not math.isfinite(args.timeout) or args.timeout <= 0:
        parser.error('Port must be 1-65535 and timeout finite and positive')
    if args.info:
        if args.x is not None or args.y is not None:
            parser.error('--info cannot be combined with coordinates')
        message = {'type': 'INFO'}
    else:
        if args.x is None or args.y is None or not all(math.isfinite(v) and v >= 0 for v in (args.x, args.y)):
            parser.error('SELECT requires finite, nonnegative --x and --y')
        message = {'type': 'SELECT', 'x': args.x, 'y': args.y, 'id': args.id or str(uuid.uuid4())}
    print('Request: ' + json.dumps(message))
    try:
        reply = send_request(message, args.port, args.timeout)
    except (OSError, ValueError) as error:
        print(f'Connection/protocol error: {error}', file=sys.stderr)
        print('Check Java is running with its control server enabled on the same port. If delivery occurred, do not retry with a new ID.', file=sys.stderr)
        return 1
    print('Java acknowledgement: ' + json.dumps(reply, indent=2))
    if reply['executed']:
        print('Action executed: the existing Swing button listeners returned successfully.')
        return 0
    if args.info and reply['status'] == 'info':
        print('INFO only: no game action requested. Use a listed control x/y with a fresh event ID.')
        return 0
    print('No new game action executed: ' + reply['status'])
    return 2


if __name__ == '__main__':
    raise SystemExit(main())
